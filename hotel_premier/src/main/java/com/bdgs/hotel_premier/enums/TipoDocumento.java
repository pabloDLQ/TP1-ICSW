package com.bdgs.hotel_premier.enums;
/**
 * El enum <code>TipoDocumento</code> representa los tipos de documentos
 * de identidad que un huésped o usuario puede poseer dentro del sistema.<p>
 * - <code>DNI</code>: documento Nacional de Identidad.<p>
 * - <code>LE</code>: libreta de Enrolamiento.<p>
 * - <code>LC</code>: libreta Cívica.<p>
 * - <code>PASAPORTE</code>: pasaporte.<p>
 * - <code>OTRO</code>: otro tipo de documento no especificado.
 *
 * @author Juan Cruz Ganis
 * @author Valentin Scilingo  
 * @author Marcos Ariel Bude
 * @author Pablo Dellacqua
 */

public enum TipoDocumento {
    DNI,
    LE,
    LC,
    PASAPORTE,
    OTRO
}
